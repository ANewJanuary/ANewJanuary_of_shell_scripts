#!/usr/bin/env python3
"""Bake text lines into a shader as a 5x7 pixel font.

In the .frag, write the lines in a comment block:

    // @text
    // TRACE      SIGNAL TRACE:
    // SYNC_A     SYNC: DEGRADED
    // @endtext

(first word = name, rest of the line = text, upper case only), then run

    gentext.py shader.frag

It (re)writes the block between "// @gen" and "// @endgen" with:
  FONT[]      glyph columns (only the glyphs used)
  TXT[]       glyph indices of all lines back to back
  T_<NAME>    line start in TXT,  N_<NAME> line length
Use it from the shader with the helpers in the same generated block:
  float textLine(vec2 p, int start, int len)   p in font pixels, origin = bottom-left
"""
import re, sys

# Classic 5x7 font, column-major, bit 0 = top row.
F = {
 ' ': [0,0,0,0,0], '!': [0,0,0x5F,0,0], '#': [0x14,0x7F,0x14,0x7F,0x14],
 '%': [0x23,0x13,0x08,0x64,0x62], '(': [0,0x1C,0x22,0x41,0], ')': [0,0x41,0x22,0x1C,0],
 '*': [0x14,0x08,0x3E,0x08,0x14], '+': [0x08,0x08,0x3E,0x08,0x08], ',': [0,0x50,0x30,0,0],
 '-': [0x08,0x08,0x08,0x08,0x08], '.': [0,0x60,0x60,0,0], '/': [0x20,0x10,0x08,0x04,0x02],
 '0': [0x3E,0x51,0x49,0x45,0x3E], '1': [0,0x42,0x7F,0x40,0], '2': [0x42,0x61,0x51,0x49,0x46],
 '3': [0x21,0x41,0x45,0x4B,0x31], '4': [0x18,0x14,0x12,0x7F,0x10], '5': [0x27,0x45,0x45,0x45,0x39],
 '6': [0x3C,0x4A,0x49,0x49,0x30], '7': [0x01,0x71,0x09,0x05,0x03], '8': [0x36,0x49,0x49,0x49,0x36],
 '9': [0x06,0x49,0x49,0x29,0x1E], ':': [0,0x36,0x36,0,0], '<': [0x08,0x14,0x22,0x41,0],
 '=': [0x14,0x14,0x14,0x14,0x14], '>': [0,0x41,0x22,0x14,0x08], '?': [0x02,0x01,0x51,0x09,0x06],
 'A': [0x7E,0x11,0x11,0x11,0x7E], 'B': [0x7F,0x49,0x49,0x49,0x36], 'C': [0x3E,0x41,0x41,0x41,0x22],
 'D': [0x7F,0x41,0x41,0x22,0x1C], 'E': [0x7F,0x49,0x49,0x49,0x41], 'F': [0x7F,0x09,0x09,0x09,0x01],
 'G': [0x3E,0x41,0x49,0x49,0x7A], 'H': [0x7F,0x08,0x08,0x08,0x7F], 'I': [0,0x41,0x7F,0x41,0],
 'J': [0x20,0x40,0x41,0x3F,0x01], 'K': [0x7F,0x08,0x14,0x22,0x41], 'L': [0x7F,0x40,0x40,0x40,0x40],
 'M': [0x7F,0x02,0x0C,0x02,0x7F], 'N': [0x7F,0x04,0x08,0x10,0x7F], 'O': [0x3E,0x41,0x41,0x41,0x3E],
 'P': [0x7F,0x09,0x09,0x09,0x06], 'Q': [0x3E,0x41,0x51,0x21,0x5E], 'R': [0x7F,0x09,0x19,0x29,0x46],
 'S': [0x46,0x49,0x49,0x49,0x31], 'T': [0x01,0x01,0x7F,0x01,0x01], 'U': [0x3F,0x40,0x40,0x40,0x3F],
 'V': [0x1F,0x20,0x40,0x20,0x1F], 'W': [0x3F,0x40,0x38,0x40,0x3F], 'X': [0x63,0x14,0x08,0x14,0x63],
 'Y': [0x07,0x08,0x70,0x08,0x07], 'Z': [0x61,0x51,0x49,0x45,0x43], '[': [0,0x7F,0x41,0x41,0],
 ']': [0,0x41,0x41,0x7F,0], '_': [0x40,0x40,0x40,0x40,0x40], '|': [0,0,0x7F,0,0],
}

def main(path):
    src = open(path).read()
    m = re.search(r"// @text\n(.*?)// @endtext", src, re.S)
    if not m: sys.exit("no // @text block")
    lines = []
    for raw in m.group(1).splitlines():
        raw = raw.lstrip("/").rstrip()
        if not raw.strip(): continue
        name, _, text = raw.strip().partition(" ")
        text = text.strip().upper().replace("~", " ")   # ~ = space that survives whitespace trimming
        bad = set(text) - set(F)
        if bad: sys.exit(f"unsupported chars in {name}: {bad}")
        lines.append((name, text))

    glyphs = sorted({c for _, t in lines for c in t}, key=lambda c: (c != ' ', c))
    gi = {c: i for i, c in enumerate(glyphs)}
    txt, defs, pos = [], [], 0
    for name, t in lines:
        defs.append(f"#define T_{name} {pos}\n#define N_{name} {len(t)}")
        txt += [gi[c] for c in t]; pos += len(t)

    font = ",".join(f"{v}u" for c in glyphs for v in F[c])
    tx = ",".join(map(str, txt))
    gen = f"""// @gen  (generated by tools/gentext.py from the @text block - don't edit by hand)
const uint FONT[{len(glyphs) * 5}] = uint[]({font});
const int TXT[{len(txt)}] = int[]({tx});
{chr(10).join(defs)}
// p in font pixels (glyph = 5x7, advance 6), origin bottom-left of the line.
// One glyph, q in font pixels inside its 6x7 cell.
float glyphPix(vec2 q, int g) {{
    int col = int(q.x), row = 6 - int(q.y);
    if (col < 0 || col > 4 || row < 0 || row > 6) return 0.0;
    return float((FONT[g * 5 + col] >> uint(row)) & 1u);
}}
float textLine(vec2 p, int start, int len) {{
    if (p.y < 0.0 || p.y >= 7.0 || p.x < 0.0 || p.x >= float(len) * 6.0) return 0.0;
    int ci = int(p.x) / 6;
    return glyphPix(vec2(p.x - float(ci * 6), p.y), TXT[start + ci]);
}}
// @endgen"""
    if "// @gen" in src:
        src = re.sub(r"// @gen.*?// @endgen", lambda _: gen, src, flags=re.S)
    else:
        src = src.replace("// @endtext", "// @endtext\n" + gen, 1)
    open(path, "w").write(src)
    print(f"{path}: {len(lines)} lines, {len(glyphs)} glyphs, {len(txt)} chars")

for p in sys.argv[1:]: main(p)
